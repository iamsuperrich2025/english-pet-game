function vfFly(actor,input,cam,arena){
  let t=0,maxY=actor.y,impact=null;
  for(let i=0;i<280;i++){
    actor.tick(0.016,i===0?input:{moveX:input.moveX||0,moveZ:input.moveZ||0,jump:false},cam,arena);
    if(actor.y>maxY) maxY=actor.y;
    t+=0.016;
    (actor.consumePowerJumpEvents()||[]).forEach(function(ev){ if(ev.type==='impact') impact=ev; });
    if(i>2&&actor.grounded) break;
  }
  return {t:t,maxY:maxY,impact:impact,x:actor.x,z:actor.z,y:actor.y,grounded:actor.grounded};
}
