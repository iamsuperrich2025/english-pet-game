function addExp(amount, p){
  p = p || activePet();
  if(!p || amount <= 0) return;
  p.exp += amount;
  while(p.exp >= expNeed(p.level)){
    p.exp -= expNeed(p.level);
    p.level++;
    if(p.level === 2){
      // ???????????/????? ? ??????????????????????????????????? (????????????????????)
      p.fedUpTo = currentSlotStart(Date.now());
      p.fullness = MEAL_FULL; p.mealSlot = p.fedUpTo;
      p.heatFrom = null;
      p.sick = false; p.sickCause = null;
    }
    showLevelUp(p);
  }
}

